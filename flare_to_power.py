import numpy as np
import matplotlib.pyplot as plt
import matplotlib
matplotlib.rcParams.update({'font.size':13})

#a flare gas-to-power with control logic
#it will add a threshold-based control rule: the system decides, hour by hour
#whether to route captured gas to the generator (ON) or hold it back (OFF),
#based on facility demand and storage state.
#an illustrative model with assumed figures,and not real facility data

hours = np.arange(0, 48,1)

np.random.seed(11)
base_flare_volume = 60 + 40 * np.sin((hours % 24 - 5) * np.pi / 12)

base_flare_volume = np.clip(base_flare_volume, 10, None)
noise = np.random.normal(0, 5,
                         size=hours.shape)
flare_gas_volume = np.clip(base_flare_volume + noise, 0, None)

capture_efficiency = 0.85
captured_gas = flare_gas_volume * capture_efficiency

energy_content_kwh_per_m3 = 10
generator_efficiency = 0.35
potential_electricity_kwh = captured_gas * energy_content_kwh_per_m3 * generator_efficiency

facility_demand_kwh = 900 + 150 * np.sin((hours % 24-8) * np.pi/16)

#CONTROL LOGIC
#It will only run the generator (convert gas to power)if there is gas reserve available and
#facility demands exceeds a threshold
#OR if the gas reserve tank is above a "must release" level
#Otherwise, store the captured gas in a small buffer instead of converting it.

gas_reserve = 0.0 #m, buffered captured gas not yet converted
reserve_capacity = 150.0 #m3, max buffer before forced release
demand_threshold = 950.0 #kW/hr - only generate when demand is above this

generator_state = [] # 'ON', 'OFF' each hour.
electricity_generated = np.zeros(len(hours), dtype=float)
reserve_trace = np.zeros(len(hours), dtype=float)

for i in range(len(hours)):
  gas_reserve += captured_gas[i] #add this hours captured gas to buffer

  must_release = gas_reserve >= reserve_capacity
  demand_high = facility_demand_kwh[i] >= demand_threshold

  if must_release or demand_high:
    #convert as much reserve as its useful this hour.
    gas_to_convert = gas_reserve
    electricity_generated[i] = gas_to_convert * energy_content_kwh_per_m3 * generator_efficiency
    gas_reserve = 0.0
    generator_state.append('ON')
  else:
    electricity_generated[i] = 0.0
    generator_state.append('OFF')
  reserve_trace[i] = gas_reserve

  demand_met = np.minimum(electricity_generated, facility_demand_kwh)
  cum_electricity = np.cumsum(electricity_generated)
  on_mask = np.array(generator_state) == 'ON'

#PLOT

fig, axes = plt.subplots(4, 1, figsize = (8, 12), sharex = True)

axes[0].plot(hours, facility_demand_kwh, color= '#5f6b66', linewidth = 2, linestyle = '--', label = 'Facility Demand')

axes[0].axhline(demand_threshold, color = '#e8823a', linestyle =':', linewidth = 1.5, label = 'Demand Threshold(control trigger)')

axes[0].set_title('1. Facility Demand vs. Control Threshold', fontsize = 13, loc ='left')
axes[0].set_ylabel('kWh/hr')
axes[0].legend(loc='upper right', fontsize = 9)
axes[0].grid(alpha=0.25)

axes[1].plot(hours, reserve_trace, color = '#3d8a76', linewidth = 2, label = 'Gas Reserve (buffer)')
axes[1].axhline(reserve_capacity, color = '#e8823a', linestyle =':', linewidth = 1.5, label = 'Buffer Capacity (forced release)')
axes[1].set_title('2. Captured Gas Reserve Level', fontsize = 13, loc ='left')
axes[1].set_ylabel('Gas (m3)')
axes[1].legend(loc='upper right', fontsize = 9)
axes[1].grid(alpha=0.25)

axes[2].fill_between(hours, 0, 1, where = on_mask, color = '#5fb8a3', alpha = 0.4, step = 'mid', label = 'Generator ON')
axes[2].fill_between(hours, 0, 1, where = ~on_mask, color = '#d8dcd9', alpha = 0.4, step = 'mid', label = 'Generator OFF')
axes[2].set_yticks([])
axes[2].set_title('3. Control Decision: Generator State Each Hour', fontsize = 13, loc ='left')
axes[2].legend(loc='upper right', fontsize = 9, ncol=2)

axes[3].plot(hours, cum_electricity, color = '#2f6f5f', linewidth = 2.5, label = 'Cumulative Electricity Generated')
axes[3].fill_between(hours, 0, cum_electricity, color = '#5fb8a3', alpha = 0.25)
axes[3].set_title('4. Cumulative Electricity Output (Controlled System)', fontsize = 13, loc ='left')
axes[3].set_ylabel('Energy (kWh)')
axes[3].set_xlabel('Time (hours)')
axes[3].legend(loc='upper right', fontsize = 9)
axes[3].grid(alpha=0.25)

fig.suptitle('Flare Gas-to-Power: Threshold-Based Control Logic',fontsize = 15, fontweight ='bold', y=0.995)
plt.tight_layout(rect = [0, 0, 1, 0.98])
plt.savefig('falre_to_power.png', dpi = 150, bbox_inches = 'tight')

print("Control rule: generate when demand >=", demand_threshold, "kWh/hr, OR reserve >=",
      reserve_capacity, "m3")
print("Hours generator ON:", on_mask.sum(), "of", len(hours))
print("Total electricity generated (controlled):", round(electricity_generated.sum(), 1), "kWh")
print("Total demand met:", round(demand_met.sum(),1), "kWh")
print("Share of demand offset: {:.1f}%".format(100*demand_met.sum()/facility_demand_kwh.sum()))